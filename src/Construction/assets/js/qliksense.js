function renderHeroBannerAppInfo(app) {
    if (typeof app.getAppLayout !== 'function') {
        console.warn('app.getAppLayout is not available on this Capability API version.');
        return;
    }

    app.getAppLayout().then(function (reply) {
   
        const layout = (reply && reply.layout) || reply || {};

        const appTitle = layout.qTitle;
        if (appTitle) {
            $('#heroBannerText').text("Here's a quick look at safety, incidents and compliance across " + appTitle + '.');
        }

        const lastReload = layout.qLastReloadTime;
        if (!lastReload) {
            return;
        }

        let reloadDate = new Date(lastReload);
        if (isNaN(reloadDate.getTime()) && typeof lastReload === 'number') {
            reloadDate = new Date(Date.UTC(1899, 11, 30) + lastReload * 86400000);
        }
        if (isNaN(reloadDate.getTime())) {
            return;
        }

        const el = document.getElementById('heroBannerLastReloaded');
        if (!el) {
            return;
        }
        const datePart = reloadDate.toLocaleDateString(undefined, { weekday: 'short', day: 'numeric', month: 'short' });
        const timePart = reloadDate.toLocaleTimeString(undefined, { hour: 'numeric', minute: '2-digit' });
        el.textContent = 'Data last reloaded ' + datePart + ' at ' + timePart;
    }).catch(function (err) {
        console.warn('app.getAppLayout() failed:', err);
    });
}

