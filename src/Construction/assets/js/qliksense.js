                // Wraps app.getObject() in a try/catch and always returns a
                // promise, so a bad/invalid object id that throws SYNCHRONOUSLY
                // (rather than just rejecting asynchronously) can't crash the
                // surrounding array literal below and take out every other
                // object in the same batch (and everything after it in this
                // function) with it.
                function safeGetObject(elementId, objectId) {
                    const maxAttempts = 3;

                    function attempt(attemptNumber) {
                        try {
                            return Promise.resolve(app.getObject(elementId, objectId)).catch(function (err) {
                                if (attemptNumber >= maxAttempts) {
                                    return Promise.reject(err);
                                }
                                return new Promise(function (resolve) {
                                    setTimeout(resolve, attemptNumber * 350);
                                }).then(function () {
                                    return attempt(attemptNumber + 1);
                                });
                            });
                        } catch (err) {
                            if (attemptNumber >= maxAttempts) {
                                return Promise.reject(err);
                            }
                            return new Promise(function (resolve) {
                                setTimeout(resolve, attemptNumber * 350);
                            }).then(function () {
                                return attempt(attemptNumber + 1);
                            });
                        }
                    }

                    return attempt(1);
                }

